let breathingRunning = false;

let breathingTimer = null;

let breathingTimeout = null;


function setupBreathingExercise() {

    const startBtn =
        document.getElementById("startBreathingBtn");

    const circle =
        document.getElementById("breathingCircle");

    const status =
        document.getElementById("breathingStatus");

    const count =
        document.getElementById("breathingCount");

    const roundText =
        document.getElementById("breathingRound");


    // Breathing exercise may not currently be rendered

    if (
        !startBtn ||
        !circle ||
        !status ||
        !count
    ) {

        return;

    }


    startBtn.addEventListener("click", () => {

        if (breathingRunning) {

            stopBreathingExercise();

            return;

        }


        breathingRunning = true;


        startBtn.innerHTML = `

            <i class="fa-solid fa-stop"></i>

            Stop Exercise

        `;


        runBreathingExercise(
            circle,
            status,
            count,
            roundText,
            startBtn
        );

    });

}


function runBreathingExercise(
    circle,
    status,
    count,
    roundText,
    startBtn
) {

    let round = 1;

    const totalRounds = 5;


    function startRound() {

        if (!breathingRunning) return;


        if (round > totalRounds) {

            completeBreathingExercise(
                circle,
                status,
                count,
                roundText,
                startBtn
            );

            return;

        }


        roundText.textContent =
            `Round ${round} of ${totalRounds}`;


        // Breathe In

        runBreathingPhase(

            circle,

            status,

            count,

            "Breathe In",

            4,

            "breathe-in",

            () => {


                // Hold

                runBreathingPhase(

                    circle,

                    status,

                    count,

                    "Hold",

                    4,

                    "hold",

                    () => {


                        // Breathe Out

                        runBreathingPhase(

                            circle,

                            status,

                            count,

                            "Breathe Out",

                            6,

                            "breathe-out",

                            () => {


                                // Rest

                                runBreathingPhase(

                                    circle,

                                    status,

                                    count,

                                    "Rest",

                                    2,

                                    "rest",

                                    () => {

                                        round++;

                                        startRound();

                                    }

                                );

                            }

                        );

                    }

                );

            }

        );

    }


    startRound();

}


function runBreathingPhase(
    circle,
    status,
    count,
    phaseName,
    seconds,
    phaseClass,
    callback
) {

    if (!breathingRunning) return;


    clearInterval(breathingTimer);

    clearTimeout(breathingTimeout);


    circle.classList.remove(
        "breathe-in",
        "hold",
        "breathe-out",
        "rest"
    );


    // Force browser to register class removal

    void circle.offsetWidth;


    circle.classList.add(phaseClass);


    status.textContent =
        phaseName;


    let remaining =
        seconds;


    count.textContent =
        remaining;


    breathingTimer = setInterval(() => {

        remaining--;


        if (remaining > 0) {

            count.textContent =
                remaining;

        }

    }, 1000);


    breathingTimeout = setTimeout(() => {

        clearInterval(breathingTimer);


        if (breathingRunning) {

            callback();

        }

    }, seconds * 1000);

}


function stopBreathingExercise() {

    breathingRunning = false;


    clearInterval(breathingTimer);

    clearTimeout(breathingTimeout);


    const circle =
        document.getElementById("breathingCircle");

    const status =
        document.getElementById("breathingStatus");

    const count =
        document.getElementById("breathingCount");

    const roundText =
        document.getElementById("breathingRound");

    const startBtn =
        document.getElementById("startBreathingBtn");


    if (circle) {

        circle.classList.remove(
            "breathe-in",
            "hold",
            "breathe-out",
            "rest"
        );

    }


    if (status) {

        status.textContent = "Ready";

    }


    if (count) {

        count.textContent = "4";

    }


    if (roundText) {

        roundText.textContent =
            "5 calming rounds";

    }


    if (startBtn) {

        startBtn.innerHTML = `

            <i class="fa-solid fa-play"></i>

            Start Exercise

        `;

    }

}


function completeBreathingExercise(
    circle,
    status,
    count,
    roundText,
    startBtn
) {

    breathingRunning = false;


    clearInterval(breathingTimer);

    clearTimeout(breathingTimeout);


    circle.classList.remove(
        "breathe-in",
        "hold",
        "breathe-out",
        "rest"
    );


    status.textContent =
        "Complete";


    count.textContent =
        "✓";


    roundText.textContent =
        "Nice work. Take a moment before moving on.";


    startBtn.innerHTML = `

        <i class="fa-solid fa-rotate-right"></i>

        Start Again

    `;

}

