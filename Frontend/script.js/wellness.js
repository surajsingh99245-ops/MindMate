function renderExercises(need) {


    // Stop any running exercise before changing category

    stopBreathingExercise();



    const selected =
        needExercises[need];


    if (!selected) return;


    // Change heading

    exerciseTitle.textContent =
        selected.title;


    // Clear previous exercises

    exerciseList.innerHTML = "";


    // Create exercise cards

    selected.exercises.forEach((exerciseKey) => {

        const exercise =
            exercises[exerciseKey];


        const card =
            document.createElement("div");


        card.className = "exercise-card";

        card.dataset.exercise = exerciseKey;


        card.innerHTML = `

    <button
        type="button"
        class="exercise-toggle">

        <span class="exercise-icon">
            ${exercise.icon}
        </span>

        <span class="exercise-info">

            <span class="exercise-name">
                ${exercise.title}
            </span>

            <span class="exercise-description">
                ${exercise.description}
            </span>

        </span>

        <i class="fa-solid fa-chevron-down exercise-arrow"></i>

    </button>


<div class="exercise-content">

    <div class="exercise-content-inner">

        ${exercise.content
                ? exercise.content
                : `
                    <p>
                        ${exercise.description}
                    </p>

                    <span class="exercise-coming">
                        Exercise ready to begin.
                    </span>
                `
            }

    </div>

</div>

`;


        exerciseList.appendChild(card);

    });



    // ================= ACCORDION =================

    const exerciseCards =
        exerciseList.querySelectorAll(".exercise-card");


    exerciseCards.forEach((card) => {

        const toggle =
            card.querySelector(".exercise-toggle");


        toggle.addEventListener("click", () => {

            const isOpen =
                card.classList.contains("active");


            // Close all exercise cards

            exerciseCards.forEach((item) => {

                item.classList.remove("active");

            });


            // Open clicked card if it wasn't already open

            if (!isOpen) {

                card.classList.add("active");

            }

        });

    });




    // Show section

    exerciseSection.classList.add("show");


    // Setup interactive exercises

    setupBreathingExercise();

    setupGroundingExercise();


    // Smoothly move toward exercises

    setTimeout(() => {

        exerciseSection.scrollIntoView({

            behavior: "smooth",

            block: "start"

        });

    }, 100);

}


