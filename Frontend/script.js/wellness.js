const groundingSteps = [

    {
        number: 5,

        sense: "Things You Can See",

        instruction:
            "Look around slowly and notice five things you can see. Pay attention to colors, shapes, light, and small details."
    },

    {
        number: 4,

        sense: "Things You Can Touch",

        instruction:
            "Notice four things you can physically feel, such as your clothing, the chair beneath you, or the surface near you."
    },

    {
        number: 3,

        sense: "Things You Can Hear",

        instruction:
            "Pause and listen carefully. Notice three sounds around you, even quiet or distant ones."
    },

    {
        number: 2,

        sense: "Things You Can Smell",

        instruction:
            "Notice two scents around you. If you cannot smell anything clearly, think of two familiar scents you enjoy."
    },

    {
        number: 1,

        sense: "Thing You Can Taste",

        instruction:
            "Notice one taste in your mouth right now, or think about a familiar taste that feels comforting."
    }

];

function setupGroundingExercise() {

    const stepContent =
        document.getElementById("groundingStepContent");

    const stepLabel =
        document.getElementById("groundingStep");

    const progressBar =
        document.getElementById("groundingProgressBar");

    const previousBtn =
        document.getElementById("groundingPreviousBtn");

    const nextBtn =
        document.getElementById("groundingNextBtn");


    // Grounding may not currently be rendered

    if (
        !stepContent ||
        !stepLabel ||
        !progressBar ||
        !previousBtn ||
        !nextBtn
    ) {

        return;

    }


    let currentStep = 0;


    function renderGroundingStep() {

        const step =
            groundingSteps[currentStep];


        stepLabel.textContent =
            `Step ${currentStep + 1} of ${groundingSteps.length}`;


        progressBar.style.width =
            `${((currentStep + 1) / groundingSteps.length) * 100}%`;


        stepContent.innerHTML = `

            <span class="grounding-number">
                ${step.number}
            </span>

            <span class="grounding-sense">
                ${step.sense}
            </span>

            <p class="grounding-instruction">
                ${step.instruction}
            </p>

        `;


        previousBtn.disabled =
            currentStep === 0;


        if (
            currentStep ===
            groundingSteps.length - 1
        ) {

            nextBtn.innerHTML = `

                Complete

                <i class="fa-solid fa-check"></i>

            `;

        } else {

            nextBtn.innerHTML = `

                Next

                <i class="fa-solid fa-arrow-right"></i>

            `;

        }

    }


    renderGroundingStep();

    previousBtn.addEventListener("click", () => {

        if (currentStep > 0) {

            currentStep--;

            renderGroundingStep();

        }

    });


    nextBtn.addEventListener("click", () => {

        if (
            currentStep <
            groundingSteps.length - 1
        ) {

            currentStep++;

            renderGroundingStep();

            return;

        }


        // Exercise completed

        stepLabel.textContent =
            "Complete";


        progressBar.style.width =
            "100%";


        stepContent.innerHTML = `

            <div class="grounding-complete">

                <div class="grounding-complete-icon">

                    <i class="fa-solid fa-check"></i>

                </div>

                <h3>
                    Grounding Complete
                </h3>

                <p>
                    Take one slow breath and notice how
                    you feel before moving on.
                </p>

            </div>

        `;


        previousBtn.style.display =
            "none";


        nextBtn.innerHTML = `

            <i class="fa-solid fa-rotate-right"></i>

            Start Again

        `;


        nextBtn.onclick = () => {

            currentStep = 0;

            previousBtn.style.display = "";

            nextBtn.onclick = null;

            renderGroundingStep();

        };

    });

}









